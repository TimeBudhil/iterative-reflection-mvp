CREATE TABLE tag_categories (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL,
  display_order INT NOT NULL,
  CONSTRAINT tag_categories_name_uq UNIQUE (name)
);

CREATE TABLE tags (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL,
  name        VARCHAR(100) NOT NULL,
  CONSTRAINT tags_category_fk FOREIGN KEY (category_id) REFERENCES tag_categories (id),
  CONSTRAINT tags_category_name_uq UNIQUE (category_id, name)
);

CREATE TABLE careers (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title             VARCHAR(200) NOT NULL,
  summary           VARCHAR(2000) NOT NULL,
  estimated_minutes INT NOT NULL,
  default_order     INT NOT NULL,
  active            BOOLEAN NOT NULL,
  CONSTRAINT careers_title_uq UNIQUE (title)
);

CREATE TABLE career_tags (
  career_id BIGINT NOT NULL,
  tag_id    BIGINT NOT NULL,
  PRIMARY KEY (career_id, tag_id),
  CONSTRAINT career_tags_career_fk FOREIGN KEY (career_id) REFERENCES careers (id),
  CONSTRAINT career_tags_tag_fk FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE TABLE career_pages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  career_id   BIGINT NOT NULL,
  page_number INT NOT NULL,
  title       VARCHAR(200),
  CONSTRAINT career_pages_career_fk FOREIGN KEY (career_id) REFERENCES careers (id),
  CONSTRAINT career_pages_number_uq UNIQUE (career_id, page_number)
);

CREATE TABLE content_blocks (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id     BIGINT NOT NULL,
  block_order INT NOT NULL,
  block_type  VARCHAR(20) NOT NULL,
  body        VARCHAR(10000),
  url         VARCHAR(2000),
  label       VARCHAR(200),
  CONSTRAINT content_blocks_page_fk FOREIGN KEY (page_id) REFERENCES career_pages (id),
  CONSTRAINT content_blocks_order_uq UNIQUE (page_id, block_order),
  CONSTRAINT content_blocks_type_ck CHECK (block_type IN ('TEXT', 'VIDEO_EMBED', 'AUDIO_EMBED', 'IMAGE_URL', 'EXTERNAL_LINK'))
);

CREATE TABLE page_progress (
  student_id        BIGINT NOT NULL,
  career_id         BIGINT NOT NULL,
  last_viewed_page  INT NOT NULL,
  updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY (student_id, career_id),
  CONSTRAINT page_progress_student_fk FOREIGN KEY (student_id) REFERENCES users (id),
  CONSTRAINT page_progress_career_fk FOREIGN KEY (career_id) REFERENCES careers (id)
);
