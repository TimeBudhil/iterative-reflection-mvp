CREATE TABLE affinity_contributions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  BIGINT NOT NULL,
  tag_id      BIGINT NOT NULL,
  source_type VARCHAR(16) NOT NULL,
  source_id   BIGINT NOT NULL,
  delta       DOUBLE PRECISION NOT NULL,
  CONSTRAINT affinity_source_type_ck CHECK (source_type IN ('REFLECTION', 'INTAKE', 'ABANDON')),
  CONSTRAINT affinity_student_fk FOREIGN KEY (student_id) REFERENCES users (id),
  CONSTRAINT affinity_tag_fk FOREIGN KEY (tag_id) REFERENCES tags (id),
  CONSTRAINT affinity_unique UNIQUE (student_id, tag_id, source_type, source_id)
);
CREATE INDEX affinity_student_source_idx ON affinity_contributions (student_id, source_type, source_id);
