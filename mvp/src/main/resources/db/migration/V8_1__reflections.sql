CREATE TABLE reflection_questions (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_key  VARCHAR(50) NOT NULL,
  version       INT NOT NULL,
  prompt        VARCHAR(500) NOT NULL,
  open_prompt   VARCHAR(500),
  display_order INT NOT NULL,
  active        BOOLEAN NOT NULL,
  CONSTRAINT reflection_questions_key_version_uq UNIQUE (question_key, version)
);

CREATE TABLE reflections (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id      BIGINT NOT NULL,
  career_id       BIGINT NOT NULL,
  current_version INT NOT NULL,
  version         BIGINT NOT NULL,
  created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT reflections_student_career_uq UNIQUE (student_id, career_id),
  CONSTRAINT reflections_student_fk FOREIGN KEY (student_id) REFERENCES users (id),
  CONSTRAINT reflections_career_fk FOREIGN KEY (career_id) REFERENCES careers (id)
);

CREATE INDEX reflections_student_updated_idx ON reflections (student_id, updated_at);

CREATE TABLE reflection_versions (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reflection_id  BIGINT NOT NULL,
  version_number INT NOT NULL,
  verdict        VARCHAR(10) NOT NULL,
  created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT reflection_versions_uq UNIQUE (reflection_id, version_number),
  CONSTRAINT reflection_versions_reflection_fk FOREIGN KEY (reflection_id) REFERENCES reflections (id),
  CONSTRAINT reflection_versions_verdict_ck CHECK (verdict IN ('YES', 'MAYBE', 'NO'))
);

CREATE TABLE reflection_answers (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reflection_version_id BIGINT NOT NULL,
  question_id           BIGINT NOT NULL,
  score                 INT NOT NULL,
  open_text             VARCHAR(1000),
  CONSTRAINT reflection_answers_uq UNIQUE (reflection_version_id, question_id),
  CONSTRAINT reflection_answers_version_fk FOREIGN KEY (reflection_version_id) REFERENCES reflection_versions (id),
  CONSTRAINT reflection_answers_question_fk FOREIGN KEY (question_id) REFERENCES reflection_questions (id),
  CONSTRAINT reflection_answers_score_ck CHECK (score BETWEEN 1 AND 10)
);

