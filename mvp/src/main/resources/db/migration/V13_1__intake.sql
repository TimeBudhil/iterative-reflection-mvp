CREATE TABLE intake_questions (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_key  VARCHAR(50) NOT NULL,
  prompt        VARCHAR(500) NOT NULL,
  question_type VARCHAR(10) NOT NULL,
  display_order INT NOT NULL,
  active        BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT intake_questions_key_uq UNIQUE (question_key),
  CONSTRAINT intake_questions_type_ck CHECK (question_type IN ('TAGS', 'TEXT'))
);

CREATE TABLE intake_responses (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT intake_responses_student_uq UNIQUE (student_id),
  CONSTRAINT intake_responses_student_fk FOREIGN KEY (student_id) REFERENCES users (id)
);

CREATE TABLE intake_answers (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  response_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  text_value  VARCHAR(2000),
  CONSTRAINT intake_answers_uq UNIQUE (response_id, question_id),
  CONSTRAINT intake_answers_response_fk FOREIGN KEY (response_id) REFERENCES intake_responses (id),
  CONSTRAINT intake_answers_question_fk FOREIGN KEY (question_id) REFERENCES intake_questions (id)
);

CREATE TABLE intake_answer_tags (
  answer_id BIGINT NOT NULL,
  tag_id    BIGINT NOT NULL,
  PRIMARY KEY (answer_id, tag_id),
  CONSTRAINT intake_answer_tags_answer_fk FOREIGN KEY (answer_id) REFERENCES intake_answers (id),
  CONSTRAINT intake_answer_tags_tag_fk FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE TABLE intake_dismissals (
  student_id   BIGINT PRIMARY KEY,
  dismissed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT intake_dismissals_student_fk FOREIGN KEY (student_id) REFERENCES users (id)
);

