CREATE TABLE counselor_links (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    BIGINT NOT NULL,
  counselor_id  BIGINT NOT NULL,
  linked_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  revoked_at    TIMESTAMP WITH TIME ZONE,
  CONSTRAINT counselor_links_student_fk FOREIGN KEY (student_id) REFERENCES users (id),
  CONSTRAINT counselor_links_counselor_fk FOREIGN KEY (counselor_id) REFERENCES users (id),
  -- one row per pair: a relink reactivates it, so there is at most one active row per pair
  CONSTRAINT counselor_links_pair_uq UNIQUE (student_id, counselor_id)
);
CREATE INDEX counselor_links_counselor_idx ON counselor_links (counselor_id);
