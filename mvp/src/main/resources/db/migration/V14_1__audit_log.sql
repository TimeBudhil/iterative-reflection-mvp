-- Counselor detail reads, allowed and denied (R8.6). No foreign key on student_id: a denied request may name an id
-- that does not exist, and the row must still be kept.
CREATE TABLE audit_log (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  counselor_id BIGINT NOT NULL,
  student_id   BIGINT NOT NULL,
  outcome      VARCHAR(10) NOT NULL,
  at           TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT audit_log_counselor_fk FOREIGN KEY (counselor_id) REFERENCES users (id),
  CONSTRAINT audit_log_outcome_ck CHECK (outcome IN ('ALLOWED', 'DENIED'))
);
CREATE INDEX audit_log_student_idx ON audit_log (student_id, at);
