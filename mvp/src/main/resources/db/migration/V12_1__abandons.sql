CREATE TABLE abandons (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id        BIGINT NOT NULL,
  career_id         BIGINT NOT NULL,
  last_viewed_page  INT NOT NULL,
  abandon_count     INT NOT NULL,
  abandoned_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT abandons_student_fk FOREIGN KEY (student_id) REFERENCES users (id),
  CONSTRAINT abandons_career_fk FOREIGN KEY (career_id) REFERENCES careers (id),
  CONSTRAINT abandons_unique UNIQUE (student_id, career_id),
  CONSTRAINT abandons_count_check CHECK (abandon_count BETWEEN 1 AND 2)
);
