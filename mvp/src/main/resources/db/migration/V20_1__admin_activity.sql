-- Admin activity log (update 2): theme changes and counselor create/deactivate/reactivate. Internal to the admin
-- module. No foreign key on admin_id: the log is best-effort and must never block a user change; the name is
-- resolved at read time.
CREATE TABLE admin_activity (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id   BIGINT NOT NULL,
  action     VARCHAR(40) NOT NULL,
  detail     VARCHAR(2000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX admin_activity_created_idx ON admin_activity (created_at, id);
